# --- SYSTEM TO ADD INVERTED POSITIONS ---
def invert_piece(piece):
    if piece == " ":
        return " "
    if piece.islower():
        return piece.upper()
    if piece.isupper():
        return piece.lower()
    return piece

def invert_board(board):
    # Reverse the board and swap piece colors
    return [invert_piece(piece) for piece in board[::-1]]

def add_inverted_positions(dataset):
    new_positions = []
    for turn, board, label in dataset:
        inverted_board = invert_board(board)
        turn_inv = "b" if turn == "w" else "w"
        new_positions.append([turn_inv, inverted_board, label])
    dataset.extend(new_positions)

